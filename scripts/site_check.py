#!/usr/bin/env python3
"""Load the built site in a headless browser and fail on regressions.

Checks, at desktop and phone sizes:
- no JavaScript errors on any page
- axe-core finds no accessibility violations
- the map explorer has its map data and draws the list
- floating map controls do not overlap each other

Usage: uv run --extra site python scripts/site_check.py [site_dir]
Needs Chromium: uv run --extra site playwright install chromium
"""

import functools
import http.server
import sys
import threading
from itertools import combinations
from pathlib import Path

from playwright.sync_api import sync_playwright

SITE = Path(sys.argv[1] if len(sys.argv) > 1 else "site").resolve()
AXE = "https://cdn.jsdelivr.net/npm/axe-core@4.10.2/axe.min.js"
PAGES = ["", "install-guide/", "creating-custom-maps/", "xml-reference/", "maps/"]
SIZES = {"desktop": (1440, 900), "phone": (390, 844)}
FLOATING = [
    "#stack",
    "#note.on",
    ".leaflet-control-zoom",
    "#hud",
    "#info",
    ".leaflet-control-attribution",
]

# .md-code__nav: Material's code-copy buttons, generated by its own script.
AXE_RUN = """async () => {
  const res = await axe.run(
    {exclude: [['.md-code__nav']]},
    {resultTypes: ['violations'], rules: {region: {enabled: false}}});
  return res.violations.map(v => {
    const where = v.nodes.slice(0, 2).map(n => n.target.join(' ')).join(', ');
    return `${v.id} (${v.impact}) x${v.nodes.length}: ${where}`;
  });
}"""
BOX = """sel => {
  const e = document.querySelector(sel); if (!e) return null;
  const r = e.getBoundingClientRect(), cs = getComputedStyle(e);
  const shown = r.width && r.height && cs.display !== 'none'
    && cs.visibility !== 'hidden' && +cs.opacity > .05;
  return shown ? [r.left, r.top, r.right, r.bottom] : null;
}"""


class _Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args):  # keep CI output to the findings
        pass


def serve() -> str:
    handler = functools.partial(_Quiet, directory=str(SITE))
    httpd = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    return f"http://127.0.0.1:{httpd.server_address[1]}/"


def main() -> int:
    base, problems = serve(), []
    with sync_playwright() as p:
        browser = p.chromium.launch()
        for size, (w, h) in SIZES.items():
            for path in PAGES:
                page = browser.new_page(viewport={"width": w, "height": h})
                errors: list[str] = []
                page.on("pageerror", lambda e, errors=errors: errors.append(str(e)))
                page.goto(base + path)
                page.wait_for_timeout(1500)
                where = f"{size} /{path}"
                problems += [f"{where}: JavaScript error: {e}" for e in errors]
                page.add_script_tag(url=AXE)
                problems += [
                    f"{where}: accessibility: {v}" for v in page.evaluate(AXE_RUN)
                ]
                if path == "maps/":
                    n = page.evaluate("(window.ATAK_MAPS || []).length")
                    rows = page.locator("#list .item").count()
                    if not n or not rows:
                        problems.append(
                            f"{where}: explorer has {n} maps and {rows} list rows"
                        )
                    boxes = {sel: page.evaluate(BOX, sel) for sel in FLOATING}
                    for (a, ra), (b, rb) in combinations(
                        [(k, v) for k, v in boxes.items() if v], 2
                    ):
                        ix = min(ra[2], rb[2]) - max(ra[0], rb[0])
                        iy = min(ra[3], rb[3]) - max(ra[1], rb[1])
                        if ix > 2 and iy > 2:
                            problems.append(
                                f"{where}: {a} overlaps {b} ({int(ix)}×{int(iy)} px)"
                            )
                page.close()
        browser.close()
    for line in problems:
        print("FAIL", line)
    print(f"{len(PAGES) * len(SIZES)} page views checked, {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
